/**
 * The calculator catalog the server uses for "Email me this result" (packages/cloud/src/marketing): every
 * calculator's name, path and inputs, and the shapes (`shapeOf`: digits masked) of the result figures it can show.
 * The server sends only labels from this catalog and figures whose label and value match a known shape, so the
 * catalog must follow the site.
 *
 *   - Checked here on every run: the inputs are exactly the specs', and the figures of every calculator's default
 *     result match the catalog.
 *   - Regenerate after changing a calculator's inputs or figure wording (a few minutes; it runs every calculator
 *     over each option and each input's extremes):
 *       UPDATE_EMAIL_CATALOG=1 pnpm --filter @glideworth/site exec vitest run src/tools/email-catalog.test.ts
 *       pnpm format
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  CALCULATORS,
  type Catalog,
  type CatalogField,
  CURRENCY_LOCALES,
  shapeOf,
  VALUE_SHAPES,
} from "@glideworth/cloud/calculator-email";
import { describe, expect, it } from "vitest";
import { runTool } from "./engine";
import { CURRENCIES } from "./format";
import { toolMeta } from "./registry";
import { SPECS } from "./specs";
import { defaults, validate } from "./state";
import type { ToolId, ToolSpec, Values } from "./types";

const OUT = join(
  import.meta.dirname,
  "../../../../packages/cloud/src/marketing/catalog.generated.ts",
);
const IDS = Object.keys(SPECS) as ToolId[];

/** The catalog's view of a spec: what the server needs to read, check and label the inputs. */
function catalogFields(spec: ToolSpec): CatalogField[] {
  return spec.fields.map((f) => {
    const showWhen = f.showWhen
      ? { showWhen: { key: f.showWhen.key, values: [...f.showWhen.values] } }
      : {};
    return f.kind === "number"
      ? {
          key: f.key,
          label: f.label,
          kind: "number",
          unit: f.unit,
          min: f.min,
          max: f.max,
          step: f.step,
          default: f.default,
          ...showWhen,
        }
      : {
          key: f.key,
          label: f.label,
          kind: "select",
          options: f.options.map((o) => ({ value: o.value, label: o.label })),
          default: f.default,
          ...showWhen,
        };
  });
}

function inputEntry(id: ToolId) {
  const spec = SPECS[id];
  const meta = toolMeta(id);
  return {
    name: meta.name,
    path: meta.path,
    ...(spec.currency ? { currency: spec.currency } : {}),
    fields: catalogFields(spec),
  };
}

/**
 * Inputs to run for the shapes: the defaults, every option of every choice, and each number at its minimum,
 * middle and maximum (one change at a time, skipping combinations the calculator refuses). Simulations run at
 * the smallest trial count except when the trial count is the field being varied.
 */
function samples(spec: ToolSpec): Values[] {
  const base = defaults(spec);
  const trials = spec.fields.find((f) => f.key === "trials");
  if (trials?.kind === "select") base.trials = trials.options[0]!.value;
  const out: Values[] = [defaults(spec), base];
  for (const f of spec.fields) {
    const vals =
      f.kind === "select"
        ? f.options.map((o) => o.value)
        : [f.min, f.max, f.step >= 1 ? Math.round((f.min + f.max) / 2) : (f.min + f.max) / 2];
    for (const v of vals) out.push({ ...base, [f.key]: v });
  }
  return out.filter((v) => Object.keys(validate(spec, v)).length === 0);
}

describe("email catalog (packages/cloud/src/marketing/catalog.generated.ts)", () => {
  it.skipIf(!process.env.UPDATE_EMAIL_CATALOG)(
    "regenerates the catalog",
    async () => {
      const valueShapes = new Set<string>();
      const calculators: Catalog["calculators"] = {};
      for (const id of IDS) {
        const labels = new Set<string>();
        for (const v of samples(SPECS[id])) {
          let vm;
          try {
            vm = await runTool(id, v);
          } catch {
            continue; // an input combination the engine refuses: no result, no shapes
          }
          for (const f of vm.figures) {
            labels.add(shapeOf(f.label));
            valueShapes.add(shapeOf(f.value));
          }
        }
        calculators[id] = { ...inputEntry(id), labelShapes: [...labels].sort() };
      }
      const locales = Object.fromEntries(CURRENCIES.map((c) => [c.code, c.locale]));
      writeFileSync(
        OUT,
        [
          "// Generated by apps/site/src/tools/email-catalog.test.ts (UPDATE_EMAIL_CATALOG=1). Do not edit by hand.",
          'import type { CalculatorEntry } from "./catalog-types.js";',
          "",
          `export const CALCULATORS: Readonly<Record<string, CalculatorEntry>> = ${JSON.stringify(calculators)};`,
          `export const VALUE_SHAPES: readonly string[] = ${JSON.stringify([...valueShapes].sort())};`,
          `export const CURRENCY_LOCALES: Readonly<Record<string, string>> = ${JSON.stringify(locales)};`,
          "",
        ].join("\n"),
      );
    },
    1_800_000,
  );

  it("lists every calculator with exactly the site's names, paths and inputs", () => {
    expect(Object.keys(CALCULATORS).sort()).toEqual([...IDS].sort());
    for (const id of IDS) {
      const { labelShapes: _, ...entry } = CALCULATORS[id]!;
      expect(entry, id).toEqual(inputEntry(id));
    }
    expect(CURRENCY_LOCALES).toEqual(Object.fromEntries(CURRENCIES.map((c) => [c.code, c.locale])));
  });

  it("knows the shape of every figure in every calculator's default result", async () => {
    const values = new Set(VALUE_SHAPES);
    for (const id of IDS) {
      const vm = await runTool(id, defaults(SPECS[id]));
      const labels = new Set(CALCULATORS[id]!.labelShapes);
      for (const f of vm.figures) {
        expect(labels.has(shapeOf(f.label)), `${id}: label "${f.label}"`).toBe(true);
        expect(values.has(shapeOf(f.value)), `${id}: value "${f.value}"`).toBe(true);
      }
    }
  });

  it("figure shapes carry no digits: a visitor can choose numbers, never words", () => {
    for (const s of VALUE_SHAPES) expect(s).not.toMatch(/\d/);
    for (const id of IDS) for (const s of CALCULATORS[id]!.labelShapes) expect(s).not.toMatch(/\d/);
  });
});
