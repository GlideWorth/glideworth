"""
Rebuild Glideworth's bundled US historical market dataset (`us-1928`) from its public sources (see
../README.md and DATA-LICENSES.md).

Usage (run from anywhere; downloads go in a directory you choose, outside the repo):

    mkdir -p /tmp/glideworth-data
    curl -L -o /tmp/glideworth-data/histretSP.xls https://pages.stern.nyu.edu/~adamodar/pc/datasets/histretSP.xls
    python3 -I fetch_bls_cpi.py /tmp/glideworth-data          # CPI-U from the BLS Public Data API
    uv run --with xlrd python -I build_datasets.py /tmp/glideworth-data <repo>/packages/core/src/stochastic/data

It writes `us.generated.ts` (excluded from the formatter and linter, so there is no format step).
Values are rounded to 6 decimal places. No value is invented: every number is a direct arithmetic
transformation of a source cell, as documented per series below and in the README.

The UK dataset `uk-1983` has its own script (`build_uk_open.py`). The optional, unbundled US 1871
dataset for self-hosters is fetched by `fetch_shiller_local.py`.
"""
import csv
import json
import os
import sys

import xlrd

SRC, OUT = sys.argv[1], sys.argv[2]


def r6(x):
    return None if x is None else round(float(x), 6)


# ---------------------------------------------------------------- Damodaran (us-1928)
def damodaran():
    wb = xlrd.open_workbook(os.path.join(SRC, "histretSP.xls"))
    raw = wb.sheet_by_name("S&P 500 & Raw Data")
    ret = wb.sheet_by_name("Returns by year")
    price, divs, tbond_rate = {}, {}, {}
    for r in range(2, raw.nrows):
        y = raw.cell_value(r, 0)
        if not isinstance(y, float):
            continue
        y = int(y)
        price[y] = raw.cell_value(r, 1)
        divs[y] = raw.cell_value(r, 2)
        tbond_rate[y] = raw.cell_value(r, 4)
    tbill, tbond_tr, sp_tr = {}, {}, {}
    for r in range(20, ret.nrows):
        y = ret.cell_value(r, 0)
        if not isinstance(y, float):
            break
        y = int(y)
        sp_tr[y] = ret.cell_value(r, 1)
        tbill[y] = ret.cell_value(r, 3)
        tbond_tr[y] = ret.cell_value(r, 4)
    return price, divs, tbond_rate, tbill, tbond_tr, sp_tr


def cpi_u_monthly():
    """BLS CUUR0000SA0 monthly index, as written by fetch_bls_cpi.py (observation_date,CPIAUCNS)."""
    out = {}
    with open(os.path.join(SRC, "CPIAUCNS.csv")) as f:
        for row in csv.DictReader(f):
            y, m, _ = row["observation_date"].split("-")
            if not row["CPIAUCNS"]:
                continue  # e.g. October 2025 was never published (US federal shutdown)
            out[(int(y), int(m))] = float(row["CPIAUCNS"])
    return out


def build_us_1928():
    price, divs, tbond_rate, tbill, tbond_tr, sp_tr = damodaran()
    cpi = cpi_u_monthly()
    years = [y for y in sorted(sp_tr) if y - 1 in price and (y, 12) in cpi]
    s = {k: [] for k in ["stocks", "dividendYield", "bonds", "bondYield", "cash", "inflation"]}
    for y in years:
        p0, p1 = price[y - 1], price[y]
        stocks = p1 / p0 - 1
        dy = divs[y] / p0
        # Identity check against Damodaran's own total return column.
        assert abs(stocks + dy - sp_tr[y]) < 1e-9, (y, stocks + dy, sp_tr[y])
        coupon = tbond_rate[y - 1]  # bond bought at par at last year's yield
        s["stocks"].append(r6(stocks))
        s["dividendYield"].append(r6(dy))
        s["bondYield"].append(r6(coupon))
        s["bonds"].append(r6(tbond_tr[y] - coupon))
        s["cash"].append(r6(tbill[y]))
        s["inflation"].append(r6(cpi[(y, 12)] / cpi[(y - 1, 12)] - 1))
    return years, s


# A global equity series is deliberately NOT built: no openly licensed published global index
# series was found (MSCI and Dimson-Marsh-Staunton are proprietary). See README.


def ts_series(s):
    return ",\n".join(f"    {k}: {json.dumps(v)}" for k, v in s.items())


def emit(path, header, entries):
    with open(path, "w") as f:
        f.write(header + "\n" + IMPORT)
        for name, years, s, extra in entries:
            f.write(
                f"\nexport const {name}: RawHistoricalData = {{\n  firstYear: {years[0]},\n  lastYear: {years[-1]},\n{extra}  series: {{\n{ts_series(s)},\n  }},\n}};\n"
            )


GEN = "// GENERATED by data/scripts/build_datasets.py. Do not edit by hand; see data/README.md.\n"
IMPORT = "import type { RawHistoricalData } from './raw.js';\n"

if __name__ == "__main__":
    us28_y, us28 = build_us_1928()
    emit(
        os.path.join(OUT, "us.generated.ts"),
        GEN
        + "// Sources: Damodaran histretSP.xls (S&P 500, 10y T-bond, 3m T-bill); U.S. Bureau of Labor\n"
        + "// Statistics CPI-U (CUUR0000SA0, BLS Public Data API). See README for licences.\n",
        [("US_1928_RAW", us28_y, us28, "")],
    )
    print("us-1928", us28_y[0], us28_y[-1])
