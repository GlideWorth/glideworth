/** Static metadata for each AccountType: category, default tax treatment, drawdown bucket. */
import type { AccountCategory, AccountType, DrawdownCategory, TaxTreatment } from "./accounts.js";
import type { CountryCode } from "./primitives.js";

export interface AccountTypeInfo {
  label: string;
  category: AccountCategory;
  taxTreatment: TaxTreatment;
  drawdown: DrawdownCategory;
  country?: CountryCode;
  /** Penalty-free withdrawal age default, when the jurisdiction has one. */
  qualifiedAge?: number;
  /** True when contributions are capped by a jurisdiction limit. */
  hasContributionLimit?: boolean;
  /** Roth-style accounts track contribution basis. */
  tracksContributionBasis?: boolean;
  /** Taxable-style accounts track cost basis. */
  tracksCostBasis?: boolean;
  /**
   * Pension wrappers that cannot be drawn before the access age at all (UK normal minimum pension
   * age, German / Dutch / Irish / Israeli pensions, French PER, KiwiSaver) unless the account models
   * an early-withdrawal penalty. Other accounts with a qualified age are accessible early (penalised
   * when the account models a penalty).
   */
  lockedUntilAccessAge?: boolean;
  /**
   * Taxable-treatment wrappers whose income is capitalised (French PEA, assurance-vie): dividends
   * and interest are reinvested inside the wrapper, never taxed yearly and never added to the cost
   * basis, so the whole gain is taxed when withdrawn.
   */
  sheltersIncome?: boolean;
  /** Asset class used for returns. */
  assetClass: "cash" | "portfolio" | "crypto";
}

